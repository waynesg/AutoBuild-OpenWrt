src = src.replace('host:[', new_host_rules, 1)

# ---- 3. 补充 OUI: QNAP 00089B, NVIDIA 00044B ----
# oui 值是 base64(3字节前缀序列)
assert 'oui:{' in src, "oui:{ not found"
src = src.replace('oui:{', 'oui:{qnap:"AAib",nvidia:"AARL",', 1)

sys.stdout.write(src)
sys.stderr.write("injected ok\n")
