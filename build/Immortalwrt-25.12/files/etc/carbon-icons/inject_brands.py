# 幂等检查
if 'iphone_model' in src and 'aw_ultra' in src:
    sys.stdout.write(src)
    sys.stderr.write("already injected\n")
    sys.exit(0)

# ---- 1. 新增品牌条目（插入到 brands:{ 之后）----
# iPhone 机身图标（MDI cellphone-iphone）、Apple Watch 手表（MDI watch）
# QNAP / NVIDIA 来自 simple-icons
