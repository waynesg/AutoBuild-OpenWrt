# ---- 2. 在 host 数组开头插入型号级规则（最高优先级）----
# 注意：watch 规则要放在 apple 通用规则之前；iphone 同理
new_host_rules = (
    'host:['
    '["iphone","iphone_model","phone"],'
    '["apple[-_ ]?watch|watch","aw_ultra",null],'
)
