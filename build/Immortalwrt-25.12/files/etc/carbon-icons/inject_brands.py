new_brands = (
    'brands:{'
    f'iphone_model:{{n:"iPhone",p:"{iphone_path}"}},'
    f'aw_ultra:{{n:"Apple Watch Ultra",p:"{watch_path}"}},'
    f'qnap:{{n:"QNAP",p:"{qnap_path}"}},'
    f'nvidia:{{n:"NVIDIA",p:"{nvidia_path}"}},'
)
